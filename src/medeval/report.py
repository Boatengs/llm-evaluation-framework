"""Score generated answers and multiple choice results, then write the report.

    python -m medeval.report --runs out --results results
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

from .scoring import embedding_similarity, rouge
from .stats import mcnemar, paired_bootstrap, sign_test

METRICS = [
    ("avg_rouge_f", "Average ROUGE F1 (original headline metric)"),
    ("rougeL_f", "ROUGE-L F1"),
    ("rougeL_p", "ROUGE-L precision"),
    ("rougeL_r", "ROUGE-L recall"),
    ("embed_sim", "Embedding similarity to the reference"),
]
PAIRS = [("base_flashcard", "finetuned", "Fine tuned vs base, same flashcard prompt"),
         ("base_chat", "finetuned", "Fine tuned vs base asked in its own chat format")]


def load(pattern: str, runs: Path) -> pd.DataFrame:
    rows = [json.loads(line) for p in sorted(runs.glob(pattern)) for line in p.open()]
    return pd.DataFrame(rows)


def score_generations(gen: pd.DataFrame) -> pd.DataFrame:
    scores = pd.DataFrame([rouge(a, r) for a, r in zip(gen["answer"], gen["reference"], strict=True)])
    gen = pd.concat([gen.reset_index(drop=True), scores], axis=1)
    gen["embed_sim"] = embedding_similarity(gen["answer"].tolist(), gen["reference"].tolist())
    gen["ref_words"] = gen["reference"].str.split().str.len()
    return gen


def compare(gen: pd.DataFrame, subset: str) -> dict:
    d = gen[gen["set"] == subset]
    wide = {c: d[d.condition == c].set_index("id").sort_index() for c in d.condition.unique()}
    out = {"n": int(len(wide["finetuned"])), "conditions": {}, "pairs": {}}
    for c, w in wide.items():
        out["conditions"][c] = {
            **{m: float(w[m].mean()) for m, _ in METRICS},
            "median_words": float(w["words"].median()),
            "share_hit_token_limit": float(w["truncated"].mean()),
        }
    out["median_reference_words"] = float(wide["finetuned"]["ref_words"].median())
    for a, b, label in PAIRS:
        res = {"label": label}
        for m, _ in METRICS:
            res[m] = {**paired_bootstrap(wide[a][m].to_numpy(), wide[b][m].to_numpy()),
                      **sign_test(wide[a][m].to_numpy(), wide[b][m].to_numpy())}
        out["pairs"][f"{a}__{b}"] = res
    return out


def compare_mmlu(mc: pd.DataFrame) -> dict:
    mc = mc.assign(correct=mc["pred"] == mc["answer"])
    wide = mc.pivot_table(index="id", columns="condition", values="correct", aggfunc="first")
    subj = mc.drop_duplicates("id").set_index("id")["subject"]
    a, b = wide["base"].to_numpy(bool), wide["finetuned"].to_numpy(bool)
    out = {"n": int(len(wide)), "accuracy": {"base": float(a.mean()), "finetuned": float(b.mean())},
           "diff": paired_bootstrap(a.astype(float), b.astype(float)), "mcnemar": mcnemar(a, b),
           "letters_found_min": int(mc["letters_found"].min()), "by_subject": {}}
    for s in sorted(subj.unique()):
        ids = subj[subj == s].index
        out["by_subject"][s] = {"n": int(len(ids)), "base": float(wide.loc[ids, "base"].mean()),
                                "finetuned": float(wide.loc[ids, "finetuned"].mean())}
    return out


def fmt(x: float, pct: bool = False) -> str:
    return f"{x * 100:.1f}%" if pct else f"{x:.3f}"


def markdown(r: dict) -> str:
    L = ["# Results", "", "Generated by `python -m medeval.report` from the raw outputs in `results/raw/`. "
         "Intervals are 95% paired bootstrap intervals over questions; p values are exact two sided sign tests "
         "(McNemar for multiple choice).", ""]
    h = r["heldout"]
    L += [f"## Held-out Medical Meadow flashcards ({h['n']} questions)", "",
          "Questions from the 10% split the adapter never trained or selected on, with exact duplicates of "
          f"training questions removed. Median reference answer: {h['median_reference_words']:.0f} words.", "",
          "| Metric | Base, flashcard prompt | Base, chat prompt | Fine tuned |", "|---|---|---|---|"]
    c = h["conditions"]
    for m, label in METRICS:
        L.append(f"| {label} | {fmt(c['base_flashcard'][m])} | {fmt(c['base_chat'][m])} | {fmt(c['finetuned'][m])} |")
    L.append(f"| Median answer length, words | {c['base_flashcard']['median_words']:.0f} | "
             f"{c['base_chat']['median_words']:.0f} | {c['finetuned']['median_words']:.0f} |")
    L.append(f"| Answers cut off at 200 tokens | {fmt(c['base_flashcard']['share_hit_token_limit'], True)} | "
             f"{fmt(c['base_chat']['share_hit_token_limit'], True)} | {fmt(c['finetuned']['share_hit_token_limit'], True)} |")
    L.append("")
    for p in h["pairs"].values():
        L += [f"### {p['label']}", "",
              "| Metric | Difference (fine tuned minus base) | 95% interval | Fine tuned better on | p |",
              "|---|---|---|---|---|"]
        for m, label in METRICS:
            x = p[m]
            L.append(f"| {label} | {x['diff']:+.3f} | {x['ci95'][0]:+.3f} to {x['ci95'][1]:+.3f} | "
                     f"{x['b_wins']} of {x['n']} | {x['p_value']:.3g} |")
        L.append("")
    o = r["original20"]
    x = o["pairs"]["base_flashcard__finetuned"]["avg_rouge_f"]
    L += ["## The original 20 questions, rerun with greedy decoding", "",
          f"Same questions, references and flashcard prompt as version 1. Fine tuned average ROUGE "
          f"{fmt(o['conditions']['finetuned']['avg_rouge_f'])} vs base {fmt(o['conditions']['base_flashcard']['avg_rouge_f'])}; "
          f"fine tuned better on {x['b_wins']} of {x['n']} (sign test p = {x['p_value']:.3g}).", ""]
    m = r["mmlu"]
    L += [f"## MMLU medical multiple choice ({m['n']} questions)", "",
          "| Subject | Questions | Base | Fine tuned |", "|---|---|---|---|"]
    for s, v in m["by_subject"].items():
        L.append(f"| {s.replace('_', ' ')} | {v['n']} | {fmt(v['base'], True)} | {fmt(v['finetuned'], True)} |")
    L += [f"| All | {m['n']} | {fmt(m['accuracy']['base'], True)} | {fmt(m['accuracy']['finetuned'], True)} |", "",
          f"Difference {m['diff']['diff'] * 100:+.1f} points (95% interval {m['diff']['ci95'][0] * 100:+.1f} to "
          f"{m['diff']['ci95'][1] * 100:+.1f}); only the fine tuned model right on {m['mcnemar']['only_b_correct']}, "
          f"only the base right on {m['mcnemar']['only_a_correct']}, McNemar p = {m['mcnemar']['p_value']:.3g}.", ""]
    return "\n".join(L)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", type=Path, default=Path("out"))
    ap.add_argument("--results", type=Path, default=Path("results"))
    a = ap.parse_args()
    (a.results / "raw").mkdir(parents=True, exist_ok=True)
    gen = score_generations(load("generate-*.jsonl", a.runs))
    mc = load("mmlu-*.jsonl", a.runs)
    gen.to_csv(a.results / "raw" / "answers_scored.csv", index=False)
    mc.to_csv(a.results / "raw" / "mmlu_predictions.csv", index=False)
    r = {"heldout": compare(gen, "heldout"), "original20": compare(gen, "original20"), "mmlu": compare_mmlu(mc)}
    (a.results / "summary.json").write_text(json.dumps(r, indent=2))
    (a.results / "RESULTS.md").write_text(markdown(r))
    print(markdown(r))


if __name__ == "__main__":
    main()
